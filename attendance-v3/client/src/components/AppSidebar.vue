};

const ALL_NAV = [
  { to: '/import', label: '数据导入', icon: ICONS.upload, roles: ['hradmin'] },
  { to: '/attendance', label: '考勤计算', icon: ICONS.clock, roles: ['hradmin', 'deptadmin'] },
  { to: '/my', label: '我的考勤', icon: ICONS.user, roles: ['employee', 'deptadmin', 'hradmin'] },
  { to: '/export', label: '导出中心', icon: ICONS.download, roles: ['hradmin'] },
  { to: '/users', label: '用户管理', icon: ICONS.users, roles: ['hradmin'] },
  { to: '/settings/rules', label: '考勤规则', icon: ICONS.shield, roles: ['hradmin'] },
  { to: '/settings', label: '系统设置', icon: ICONS.settings, roles: ['hradmin'] },
];

const role = computed(() => Auth.getRole() || 'employee');

const navItems = computed(() => {
  return ALL_NAV.filter(item => item.roles.includes(role.value));
});

function isActive(to) {
  if (to === '/attendance' && route.path.startsWith('/attendance')) return true;
  if (to === '/settings' && route.path.startsWith('/settings') && route.path !== '/settings/rules') return true;
  if (to === '/settings/rules' && route.path === '/settings/rules') return true;
  return route.path === to;
}

function handleLogout() {
  Auth.logout();
  router.push('/login');
}
